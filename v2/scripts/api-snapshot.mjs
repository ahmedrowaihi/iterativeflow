#!/usr/bin/env node
// Snapshot each package's public .d.ts (built by tsdown into dist) into a committed
// etc/<pkg>.api.md. CI regenerates and `git diff --exit-code`s it: any public-surface
// change fails until the snapshot is updated, so the moved contract is visible in review.
// Run after `npm run build`.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// Public entry .d.ts per package (relative to dist). Content-hashed internal chunks are
// normalized below so a chunk rename alone doesn't churn the snapshot.
const ENTRIES = {
  core: ["index.d.mts", "backend.d.mts"],
  memory: ["index.d.mts"],
  postgres: ["index.d.mts"],
  dynamodb: ["index.d.mts"],
  conformance: ["index.d.mts"],
  dashboard: ["index.d.mts"],
};

const normalize = (src) => src.replace(/-[A-Za-z0-9_]{6,}\.d\.mts/g, "-<hash>.d.mts");

const etc = resolve(root, "etc");
if (!existsSync(etc)) mkdirSync(etc);

for (const [pkg, files] of Object.entries(ENTRIES)) {
  const sections = files.map((f) => {
    const path = resolve(root, "packages", pkg, "dist", f);
    return `## ${f}\n\n\`\`\`ts\n${normalize(readFileSync(path, "utf8").trim())}\n\`\`\``;
  });
  const body = `# @iterativeflow/${pkg} — public API\n\n> Generated by \`scripts/api-snapshot.mjs\`. Do not edit by hand.\n\n${sections.join("\n\n")}\n`;
  writeFileSync(resolve(etc, `${pkg}.api.md`), body);
  console.log(`etc/${pkg}.api.md`);
}
